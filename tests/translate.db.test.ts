import { afterAll, beforeAll, describe, expect, it } from "vitest";
import mongoose from "mongoose";
import { connectDb } from "@/lib/db/connect";
import { restaurants } from "@/lib/db/platform";
import { forTenant } from "@/lib/db/tenant";
import { translateLanguage, translateRestaurant } from "@/lib/translate/service";
import { collectUnits, coverage } from "@/lib/translate/units";
import { sourceHash } from "@/lib/translate/provenance";
import { FakeProvider } from "./fake-provider";

let A: string;
let B: string;
let dishId: string;
const glossary = [{ term: "Casentino", kind: "keep" as const }];

beforeAll(async () => {
  const conn = await connectDb();
  expect(conn.connection.name).toBe("menu_stories_test");
  await conn.connection.dropDatabase();
  const base = { name: { en: "Casa" }, default_language: "en", enabled_languages: ["en", "it", "hi"], currency: "EUR", status: "live" as const, brand: {} };
  A = (await restaurants.create({ ...base, slug: "tx-a" })).id;
  B = (await restaurants.create({ ...base, slug: "tx-b" })).id;
  const db = forTenant(A);
  await db.i18n.glossary.set(glossary);
  const cat = await db.categories.add({ en: "Primi" });
  const d = await db.dishes.create({
    category: cat.key, name: { en: "Tagliolini" }, description: { en: "Butter from the Casentino, 24 months." },
    context: { en: "Thin ribbon pasta." }, spice_level: 0, dietary: [], price: 2800, allergens: [], image: null, available: true, story_ids: [],
  });
  dishId = d.id;
  await forTenant(B).dishes.create({
    category: "x", name: { en: "Other tenant dish" }, description: {}, context: {}, spice_level: 0, dietary: [], price: 1, allergens: [], image: null, available: true, story_ids: [],
  });
});

afterAll(async () => {
  await mongoose.connection.dropDatabase();
  await mongoose.disconnect();
});

describe("translation service (database)", () => {
  it("translates missing units, records machine provenance, and reports a job", async () => {
    const provider = new FakeProvider();
    let changed = 0;
    const s = await translateLanguage(A, "it", { provider, onChanged: () => void changed++ });
    expect(s).toMatchObject({ lang: "it", status: "done", failed: 0 });
    expect(s.translated).toBeGreaterThanOrEqual(5); // restaurant, category, dish ×3
    expect(changed).toBe(1);

    const snap = await forTenant(A).i18n.snapshot();
    const dish = snap.dishes[0];
    expect(dish.name.it).toContain("Tagliolini");
    expect(dish.description.it).toContain("Casentino"); // glossary survived
    expect(dish.tx?.["name:it"]).toMatchObject({ by: "machine", m: "fake-strong" });
    expect(snap.restaurant.categories[0].name.it).toBeTruthy();
    expect(snap.restaurant.categories[0].tx?.["name:it"]?.by).toBe("machine");

    const job = (await forTenant(A).i18n.jobs.latest()).find((j) => j.lang === "it")!;
    expect(job).toMatchObject({ status: "done", failed_units: 0 });
    expect(job.tokens).toBeGreaterThan(0);

    // nothing left to do → no provider calls on the next run
    const again = new FakeProvider();
    expect((await translateLanguage(A, "it", { provider: again })).status).toBe("nothing");
    expect(again.calls.length).toBe(0);
  });

  it("never overwrites staff-edited text, even with force", async () => {
    const db = forTenant(A);
    const snap0 = await db.i18n.snapshot();
    const h = sourceHash(snap0.dishes[0].name.en, glossary, "it");
    await db.i18n.setStaff("dish", dishId, "name", "it", "Tagliolini della Casa", h);
    await translateLanguage(A, "it", { provider: new FakeProvider(), force: true });
    const dish = (await db.i18n.snapshot()).dishes[0];
    expect(dish.name.it).toBe("Tagliolini della Casa");
    expect(dish.tx?.["name:it"]?.by).toBe("staff");
    // other fields were regenerated by force
    expect(dish.description.it).toContain("(it)");
  });

  it("marks translations stale when the source changes; staff text is flagged, machine text regenerated", async () => {
    const db = forTenant(A);
    await db.dishes.update(dishId, { name: { en: "Tagliolini al Tartufo" }, description: { en: "Butter from the Casentino, aged 36 months." } });
    const snap = await db.i18n.snapshot();
    const cov = coverage(collectUnits(snap), "it", snap.restaurant.glossary);
    expect(cov.counts.stale).toBeGreaterThanOrEqual(1); // description (machine) is stale
    expect(cov.counts.staff_stale).toBe(1); // name (staff) needs review but is untouched
    const s = await translateLanguage(A, "it", { provider: new FakeProvider() });
    expect(s.translated).toBe(1);
    const dish = (await db.i18n.snapshot()).dishes[0];
    expect(dish.description.it).toContain("36");
    expect(dish.name.it).toBe("Tagliolini della Casa");
  });

  it("clearing a staff edit makes the unit eligible for machine translation again", async () => {
    const db = forTenant(A);
    await db.i18n.setStaff("dish", dishId, "name", "it", "", "x");
    const snap = await db.i18n.snapshot();
    expect(snap.dishes[0].name.it).toBeUndefined();
    await translateLanguage(A, "it", { provider: new FakeProvider() });
    expect((await db.i18n.snapshot()).dishes[0].tx?.["name:it"]?.by).toBe("machine");
  });

  it("only takes one job lock per language at a time", async () => {
    const db = forTenant(A);
    const first = await db.i18n.jobs.acquire("hi", 5);
    expect(first).not.toBeNull();
    expect(await db.i18n.jobs.acquire("hi", 5)).toBeNull();
    expect((await translateLanguage(A, "hi", { provider: new FakeProvider() })).status).toBe("busy");
    await db.i18n.jobs.finish(first!.id, "done");
    expect(await db.i18n.jobs.acquire("hi", 5)).not.toBeNull();
  });

  it("respects the restaurant's experimental-language switch", async () => {
    await restaurants.update(A, { allow_experimental: false });
    const s = await translateLanguage(A, "sw", { provider: new FakeProvider() });
    expect(s.status).toBe("failed");
    expect(s.error).toMatch(/switched off/);
    await restaurants.update(A, { allow_experimental: true });
  });

  it("keeps translations strictly inside the tenant", async () => {
    const other = await forTenant(B).i18n.snapshot();
    expect(other.dishes.map((d) => d.name.en)).toEqual(["Other tenant dish"]);
    expect(other.dishes[0].name.it).toBeUndefined();
    // a write aimed at tenant A's dish through tenant B's repo does nothing
    await forTenant(B).i18n.setStaff("dish", dishId, "name", "de", "Fremd", "x");
    expect((await forTenant(A).i18n.snapshot()).dishes[0].name.de).toBeUndefined();
  });

  it("translates many languages at once for machine-translation APIs, one at a time for LLMs", async () => {
    const langs = ["nl", "sv", "pl", "tr", "da"]; // Latin script: the fake provider only writes Latin or Devanagari
    const run = async (width: number | undefined) => {
      let active = 0;
      let peak = 0;
      const p = new FakeProvider();
      Object.assign(p, { maxParallelLanguages: width });
      const original = p.translate.bind(p);
      p.translate = async (req) => {
        active++;
        peak = Math.max(peak, active);
        await new Promise((r) => setTimeout(r, 30));
        const res = await original(req);
        active--;
        return res;
      };
      return { peak, out: await translateRestaurant(A, langs, { provider: p, force: true }), get: () => peak };
    };
    const wide = await run(3);
    expect(wide.out.map((o) => o.status)).toEqual(langs.map(() => "done"));
    expect(wide.get()).toBeGreaterThan(1);
    expect(wide.get()).toBeLessThanOrEqual(3);
    const narrow = await run(undefined);
    expect(narrow.get()).toBe(1);
    // every language is stored, so the diner side needs no further call
    const snap = await forTenant(A).i18n.snapshot();
    for (const l of langs) expect(snap.dishes[0].name[l]).toBeTruthy();
  });
});
